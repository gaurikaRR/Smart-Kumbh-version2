/**
 * Helper to fetch translation from dictionary or fallback to key/text.
 * Also supports calling dynamic Bhashini API if an endpoint is configured.
 */
export function getTranslation(key: string, lang: SupportedLanguage): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

/**
 * Dynamic Bhashini ULCA API Caller
 * If ULCA / Bhashini pipeline is enabled via env, requests live translation.
 */
export async function translateWithBhashini(text: string, targetLang: SupportedLanguage): Promise<string> {
  const apiKey = import.meta.env.VITE_BHASHINI_API_KEY;
  const userId = import.meta.env.VITE_BHASHINI_USER_ID;

  // If credentials are not present, return dictionary result immediately
  if (!apiKey || !userId || targetLang === 'en') {
    return getTranslation(text, targetLang);
  }

  try {
    const res = await fetch('https://dhruva-api.bhashini.gov.in/services/inference/translation', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: apiKey,
      },
      body: JSON.stringify({
        input: [{ source: text }],
        config: {
          language: {
            sourceLanguage: 'en',
            targetLanguage: targetLang,
          },
        },
      }),
    });
    if (res.ok) {
      const data = await res.json();
      return data?.output?.[0]?.target || getTranslation(text, targetLang);
    }
  } catch (err) {
    console.warn('Bhashini live API fallback to local dictionary:', err);
  }

  return getTranslation(text, targetLang);
}
